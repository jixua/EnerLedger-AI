def build_document_evidence_prompt(
    *,
    filename: str,
    batch_number: int,
    batch_count: int,
    context: str,
) -> str:
    """生成单批证据提取 Prompt。"""

    return f"""<文档信息>
文件名：{filename}
当前批次：{batch_number}/{batch_count}
</文档信息>

<文档片段>
{context}
</文档片段>

请按以下主题判断每个片段是否存在需要纳入报告的内容：
- 文档身份、产品或评价对象、报告期、联系人、责任人和核算组成员；
- 评价目标、依据、组织/时间/生命周期边界、功能单位或核算口径；
- 上游采购、内部生产、下游运输销售、使用、废弃处置回收和物料流清单；
- 核算模型、公式、活动数据、排放因子、数据库、GWP、参数版本和评价结果；
- 数据分类、来源可追溯性、量化说明、质量要求、排除项和不确定性；
- 明显的空缺、矛盾、残句、表格年度不清、引用不完整、缩写未解释或排版问题；
- 可以支持改进建议的具体事实。

必须为输入中的每个文档片段输出一条记录，顺序与输入一致，不得合并或遗漏。
每条 summary 应简洁概括该片段的有效信息和分析意义，避免复制大段原文。
每条 summary 最多 120 个汉字；issues 最多 3 条，每条最多 80 个汉字。
严格输出以下 JSON 结构：
{{
  "chunks": [
    {{
      "citation_index": 1,
      "disposition": "analyze",
      "summary": "该片段明确披露的内容及其分析意义",
      "issues": ["该片段直接支持的问题或缺口；没有则为空数组"]
    }}
  ]
}}

disposition 取值规则：
- analyze：只要片段包含任何需要在报告中体现的实质内容，就必须使用此值；
- context：仅包含封面、目录、页眉页脚等背景信息；
- duplicate：仅在内容与本批另一片段实质重复时使用，并在 summary 中写明重复对象。

不要因为内容难以归类而标记为 context；不确定时使用 analyze。"""


def build_document_analysis_prompt(
    *,
    filename: str,
    document_version: int,
    evidence_notes: str,
) -> str:
    """生成最终 Markdown 报告 Prompt。"""

    return f"""<分析对象>
文件名：{filename}
文档版本：v{document_version}
</分析对象>

<覆盖整份文档的证据摘要>
{evidence_notes}
</覆盖整份文档的证据摘要>

证据摘要是逐片段核验后的完整证据台账。「必须纳入报告」的片段都必须在正文相关章节中引用并分析，
不能只在结尾集中罗列引用，也不能仅依据末尾片段作出“未提及”或“缺失”判断。
请严格按照系统规定的 Markdown 结构输出分析报告。
在「分析限制」中明确说明：本报告是基于当前文档内容的大模型辅助分析，未接入外部基础知识库，
不能替代正式的第三方核查、审计、认证或法规意见。"""


def build_document_evidence_repair_prompt(
    *,
    original_prompt: str,
    rejected_output: str,
    validation_errors: list[str],
) -> str:
    """要求模型修复缺片段或结构无效的证据台账。"""

    errors = "\n".join(f"- {error}" for error in validation_errors)
    return f"""{original_prompt}

<未通过校验的证据输出>
{rejected_output}
</未通过校验的证据输出>

<必须修复的问题>
{errors}
</必须修复的问题>

请重新输出完整 JSON。必须逐一覆盖原始输入中的每个文档片段，不能只补写遗漏项。"""


def build_document_analysis_repair_prompt(
    *,
    filename: str,
    document_version: int,
    evidence_notes: str,
    rejected_report: str,
    validation_errors: list[str],
) -> str:
    """要求模型依据完整证据重写未通过完整性或覆盖校验的报告。"""

    errors = "\n".join(f"- {error}" for error in validation_errors)
    return f"""<分析对象>
文件名：{filename}
文档版本：v{document_version}
</分析对象>

<覆盖整份文档的证据摘要>
{evidence_notes}
</覆盖整份文档的证据摘要>

<未通过校验的报告>
{rejected_report}
</未通过校验的报告>

<必须修复的问题>
{errors}
</必须修复的问题>

请依据全部证据摘要重新输出一份完整 Markdown 报告，不要只续写残缺部分。
必须逐项覆盖所有标记为「必须纳入报告」的片段，删除所有批次级措辞，
并完整输出到「## 12. 结论与分析限制」结束。"""
